import { createClient } from "@supabase/supabase-js";

const supabaseUrl = import.meta.env.VITE_SUPABASE_URL;
const supabaseAnonKey = import.meta.env.VITE_SUPABASE_ANON_KEY;

export const isSupabaseConfigured = Boolean(supabaseUrl && supabaseAnonKey);

// Fall back to placeholder values so createClient never throws at module load —
// without this, a missing env var crashes the entire app before it can render
// anything (including a helpful error message).
export const supabase = createClient(
  supabaseUrl || "https://placeholder.supabase.co",
  supabaseAnonKey || "placeholder-anon-key"
);

export const adminApiUrl = `${supabaseUrl}/functions/v1/admin-api`;
